  // 构造 trend history 30 个时间点（10/天 × 6 天混合）
  function buildHistory() {
    const history = { stock: {}, industry: {}, concept: {}, market: [], timestamps: [] };
    const codeMap = {};
    const nameMap = {};
    DAILY.forEach(d => {
      d.top.concat(d.bottom).forEach(r => {
        if (!codeMap[r.股票代码]) {
          codeMap[r.股票代码] = r.股票简称;
          history.stock[r.股票代码] = [];
        }
      });
    });
    Object.entries(codeMap).forEach(([k, v]) => { nameMap[k] = v; });
    DAILY.forEach(d => {
      // 当日所有代表股的累计净额
      d.top.concat(d.bottom).forEach(r => {
        if (!history.stock[r.股票代码]) history.stock[r.股票代码] = [];
        history.stock[r.股票代码].push(parseAmountToYi(r.净额));
      });
    });
    // 行业
    DAILY.forEach(d => {
      d.industry.concat(d.industry_bottom).forEach(r => {
        if (!history.industry[r.行业]) history.industry[r.行业] = [];
        history.industry[r.行业].push(parseAmountToYi(r.净额));
      });
    });
    // 概念
    DAILY.forEach(d => {
      d.concept.concat(d.concept_bottom).forEach(r => {
        if (!history.concept[r.行业]) history.concept[r.行业] = [];
        history.concept[r.行业].push(parseAmountToYi(r.净额));
      });
    });
    // 大盘累计净流入(沪深两市主力)
    DAILY.forEach(d => {
      history.market.push(d.inflow - d.outflow);
    });
    // 时间戳:每天 5 个时间点
    const times = ["09:35", "10:00", "11:00", "13:30", "14:30"];
    for (let i = 0; i < 6; i++) {
      times.forEach(t => history.timestamps.push(t));
    }
    return { history, nameMap };
  }
  function parseAmountToYi(v) {
    if (v == null) return 0;
    if (typeof v === "number") return v;
    let s = String(v).trim().replace(/,/g, "");
    let mult = 1;
    if (s.endsWith("亿")) { s = s.slice(0, -1); mult = 1; }
    else if (s.endsWith("万")) { s = s.slice(0, -1); mult = 0.0001; }
    else if (s.endsWith("%")) { s = s.slice(0, -1); mult = 1; }
    const n = parseFloat(s);
    return isNaN(n) ? 0 : n * mult;
  }

